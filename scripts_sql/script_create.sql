SELECT 
    p.ID_PASAJE,
    TO_CHAR(p.FECHA_VIAJE, 'YYYY-MM-DD HH24:MI') AS FECHA_HORA,
    
    r.NOMBRE_RUTA,
    r.ORIGEN,
    r.DESTINO,
    r.TIEMPO_ESTIMADO,
    r.PRECIO_BASE AS PRECIO_RUTA,
    
    u.NUMERO_UNIDAD AS NUM_DISCO,
    u.PLACA,
    u.MARCA,
    u.MODELO,
    u.CAPACIDAD AS CAP_BUS,
    
    t.NOMBRE_TIPO AS TIPO_PASAJE,
    t.PORCENTAJE_DESCUENTO || '%' AS DESCUENTO_APLICADO,
    
    p.CEDULA_CLIENTE,
    p.NOMBRE_CLIENTE,
    p.NUMERO_ASIENTO,
    p.VALOR_FINAL AS TOTAL_PAGADO

FROM PASAJES p
JOIN RUTAS r ON p.ID_RUTA = r.ID_RUTA
JOIN UNIDADES u ON p.ID_UNIDAD = u.ID_UNIDAD
JOIN TIPOS_PASAJE t ON p.ID_TIPO = t.ID_TIPO
ORDER BY p.ID_PASAJE ASC;