CREATE TABLE RUTAS (
    ID_RUTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_RUTA VARCHAR2(100) NOT NULL, 
    ORIGEN VARCHAR2(50) NOT NULL,  
    DESTINO VARCHAR2(50) NOT NULL,     
    PRECIO_BASE NUMBER(10, 2) DEFAULT 0 CHECK (PRECIO_BASE >= 0),
    TIEMPO_ESTIMADO VARCHAR2(20)     
);

CREATE TABLE UNIDADES (
    ID_UNIDAD NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLACA VARCHAR2(10) NOT NULL UNIQUE,
    NUMERO_UNIDAD NUMBER NOT NULL,    
    CAPACIDAD NUMBER CHECK (CAPACIDAD > 0),
    MARCA VARCHAR2(50),
    MODELO VARCHAR2(50),
    ESTADO VARCHAR2(20) DEFAULT 'OPERATIVO' CHECK (ESTADO IN ('OPERATIVO', 'MANTENIMIENTO'))
);

CREATE TABLE TIPOS_PASAJE (
    ID_TIPO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_TIPO VARCHAR2(50) NOT NULL UNIQUE,
    PORCENTAJE_DESCUENTO NUMBER(5, 2) DEFAULT 0 CHECK (PORCENTAJE_DESCUENTO BETWEEN 0 AND 100)
);

CREATE TABLE PASAJES (
    ID_PASAJE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_RUTA NUMBER NOT NULL,
    ID_UNIDAD NUMBER NOT NULL,
    ID_TIPO NUMBER NOT NULL,
    FECHA_VIAJE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VALOR_FINAL NUMBER(10, 2) NOT NULL CHECK (VALOR_FINAL >= 0),
    CEDULA_CLIENTE VARCHAR2(13),
    NOMBRE_CLIENTE VARCHAR2(100),
    NUMERO_ASIENTO NUMBER NOT NULL,
    
    CONSTRAINT FK_PASAJE_RUTA FOREIGN KEY (ID_RUTA) REFERENCES RUTAS(ID_RUTA),
    CONSTRAINT FK_PASAJE_UNIDAD FOREIGN KEY (ID_UNIDAD) REFERENCES UNIDADES(ID_UNIDAD),
    CONSTRAINT FK_PASAJE_TIPO FOREIGN KEY (ID_TIPO) REFERENCES TIPOS_PASAJE(ID_TIPO)
);

